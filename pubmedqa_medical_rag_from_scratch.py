"""**Write down:** accuracy@1, accuracy@5, mrr@10 for both models.
Small improvements are normal: the base model is already decent, and PubMedQA questions often reuse words from their abstracts.

## Part 6 — Store chunks in a vector database (Chroma)

We create **one collection per embedding model**, with the same chunks but different embeddings.
`hnsw:space = cosine` tells Chroma to use cosine similarity.
"""

import chromadb

chroma = chromadb.Client()
models = {"baseline": base_model, "fine_tuned": ft_model}
collections = {}

for name, m in models.items():
    col_name = f"pubmed_{name}"
    try:
        chroma.delete_collection(col_name)       # clean start if you re-run
    except Exception:
        pass
    col = chroma.create_collection(name=col_name, metadata={"hnsw:space": "cosine"})

    embs = m.encode(chunks_df.text.tolist(), normalize_embeddings=True,
                    batch_size=64, show_progress_bar=True)

    B = 1000                                      # add in batches
    for i in range(0, len(chunks_df), B):
        col.add(
            ids=chunks_df.chunk_id[i:i+B].tolist(),
            documents=chunks_df.text[i:i+B].tolist(),
            embeddings=embs[i:i+B].tolist(),
            metadatas=[{"pubid": p} for p in chunks_df.pubid[i:i+B]],
        )
    collections[name] = col
    print(name, "→", col.count(), "chunks stored")

"""### 6.1 Vector search
Embed the question with the **same** model used for the chunks, then ask Chroma for the closest chunks.
"""

def vector_search(question, model_name, k=10):
    q_emb = models[model_name].encode([question], normalize_embeddings=True).tolist()
    res = collections[model_name].query(query_embeddings=q_emb, n_results=k)
    return [{"chunk_id": cid, "pubid": meta["pubid"], "text": doc}
            for cid, meta, doc in zip(res["ids"][0], res["metadatas"][0], res["documents"][0])]

q = test_df.question[0]
print("Q:", q, "| correct pubid:", test_df.pubid[0])
for r in vector_search(q, "fine_tuned", k=3):
    print(r["pubid"], "→", r["text"][:120], "...")

"""## Part 7 — Keyword search and hybrid search

**Why hybrid?** Vector search understands meaning ("heart attack" ≈ "myocardial infarction"), while keyword search nails exact terms (drug names, gene names). Medicine needs both.

**Reciprocal Rank Fusion (RRF):** each search gives a ranking. A chunk earns `1 / (60 + rank)` from each list, and we add the points. A chunk ranked high by **both** judges wins.
"""

from rank_bm25 import BM25Okapi

def tokenize(t):
    return re.findall(r"\w+", t.lower())

bm25 = BM25Okapi([tokenize(t) for t in chunks_df.text])

def keyword_search(question, k=10):
    scores = bm25.get_scores(tokenize(question))
    top = np.argsort(scores)[::-1][:k]
    return [{"chunk_id": chunks_df.chunk_id[i], "pubid": chunks_df.pubid[i], "text": chunks_df.text[i]}
            for i in top]

def hybrid_search(question, model_name, k=10, rrf_k=60):
    pool = max(30, k)
    fused = {}
    for results in (vector_search(question, model_name, pool), keyword_search(question, pool)):
        for rank, r in enumerate(results):
            entry = fused.setdefault(r["chunk_id"], {"doc": r, "score": 0.0})
            entry["score"] += 1.0 / (rrf_k + rank + 1)
    ranked = sorted(fused.values(), key=lambda x: x["score"], reverse=True)
    return [x["doc"] for x in ranked[:k]]

"""### 7.1 Compare all five retrieval setups
We score at the **abstract** level: several chunks from the same abstract count once.
"""

def eval_retriever(search_fn, k=10):
    hit1 = hit5 = hit10 = 0
    rr = 0.0
    for q, pid in zip(test_df.question, test_df.pubid):
        ranked = []
        for r in search_fn(q, k * 3):              # fetch extra, then dedupe abstracts
            if r["pubid"] not in ranked:
                ranked.append(r["pubid"])
        ranked = ranked[:k]
        if pid in ranked:
            pos = ranked.index(pid) + 1
            rr += 1 / pos
            hit1 += pos <= 1; hit5 += pos <= 5; hit10 += pos <= 10
    n = len(test_df)
    return {"hit@1": hit1/n, "hit@5": hit5/n, "hit@10": hit10/n, "MRR@10": rr/n}

retrieval_results = {
    "keyword (BM25)":    eval_retriever(lambda q, k: keyword_search(q, k)),
    "vector baseline":   eval_retriever(lambda q, k: vector_search(q, "baseline", k)),
    "vector fine-tuned": eval_retriever(lambda q, k: vector_search(q, "fine_tuned", k)),
    "hybrid baseline":   eval_retriever(lambda q, k: hybrid_search(q, "baseline", k)),
    "hybrid fine-tuned": eval_retriever(lambda q, k: hybrid_search(q, "fine_tuned", k)),
}
retrieval_table = pd.DataFrame(retrieval_results).T.round(3)
retrieval_table

"""## Part 8 — Load the LLM

**Llama-3.2-1B-Instruct**: small enough for a free T4.
- `float16` → half-size numbers, so it uses half the memory.
- `device_map="auto"` → puts it on the GPU automatically.

**If you get an access error:** Llama approval may not be done yet. Swap in `"Qwen/Qwen2.5-1.5B-Instruct"` (no approval needed) and mention it in your write-up.
"""

from transformers import pipeline

LLM_NAME = "meta-llama/Llama-3.2-1B-Instruct"     # fallback: "Qwen/Qwen2.5-1.5B-Instruct"

llm = pipeline("text-generation", model=LLM_NAME,
               torch_dtype=torch.float16, device_map="auto")

"""### 8.1 The prompt
A **strict prompt** keeps a small model on track: use only the context, reply with one word.
`parse_answer` uses **regex** to pull out yes / no / maybe, in case the model adds extra words.
"""

SYSTEM = ("You are a careful medical research assistant. "
          "If context is provided, base your answer only on that context. "
          "Reply with exactly one word: yes, no, or maybe.")

def build_messages(question, docs=None):
    if docs:
        context = "\n\n".join(f"[{i+1}] {d['text']}" for i, d in enumerate(docs))
        user = f"Context:\n{context}\n\nQuestion: {question}\nAnswer (yes, no, or maybe):"
    else:
        user = f"Question: {question}\nAnswer (yes, no, or maybe):"
    return [{"role": "system", "content": SYSTEM},
            {"role": "user", "content": user}]

def ask_llm(messages):
    out = llm(messages, max_new_tokens=5, do_sample=False)
    return out[0]["generated_text"][-1]["content"].strip()

def parse_answer(text):
    m = re.search(r"\b(yes|no|maybe)\b", text.lower())
    return m.group(1) if m else "unknown"

print(ask_llm(build_messages("Is regular exercise associated with lower blood pressure?")))

"""## Part 9 — The full RAG function

`mode` lets us switch retrieval on and off:
- `"none"` → LLM answers from memory only (shows why RAG matters)
- `"vector"` → meaning search only
- `"hybrid"` → meaning + keyword
"""

def rag_answer(question, model_name="fine_tuned", mode="hybrid", top_k=3):
    if mode == "none":
        docs = []
    elif mode == "hybrid":
        docs = hybrid_search(question, model_name, k=top_k)
    else:
        docs = vector_search(question, model_name, k=top_k)
    raw = ask_llm(build_messages(question, docs))
    return parse_answer(raw), raw, docs

pred, raw, docs = rag_answer(test_df.question[0])
print("Question:", test_df.question[0])
print("Predicted:", pred, "| Correct:", test_df.label[0])
print("Evidence pubids:", [d["pubid"] for d in docs])

"""## Part 10 — End-to-end evaluation

We compare three setups on the same questions:
1. **LLM only** (no retrieval)
2. **RAG + baseline embeddings**
3. **RAG + fine-tuned embeddings**

Start with `N_EVAL = 200` (~3–5 min) to make sure everything works, then set it to **1000** for final numbers.
"""

from tqdm.auto import tqdm

N_EVAL = 200          # change to 1000 for the final run
eval_df = test_df.sample(N_EVAL, random_state=SEED) if N_EVAL < len(test_df) else test_df

setups = {
    "LLM only (no retrieval)":     dict(mode="none"),
    "RAG + baseline embeddings":   dict(model_name="baseline",   mode="hybrid"),
    "RAG + fine-tuned embeddings": dict(model_name="fine_tuned", mode="hybrid"),
}

rows = []
for setup, kwargs in setups.items():
    for _, r in tqdm(eval_df.iterrows(), total=len(eval_df), desc=setup):
        pred, raw, docs = rag_answer(r.question, **kwargs)
        rows.append({"setup": setup, "pubid": r.pubid, "label": r.label, "pred": pred,
                     "gold_retrieved": any(d["pubid"] == r.pubid for d in docs)})

preds = pd.DataFrame(rows)
preds["correct"] = preds.pred == preds.label
preds.head()

"""### 10.1 Results tables
- **accuracy** → share of correct answers
- **unknown_rate** → model didn't give yes/no/maybe (a prompt-following problem)
- **gold_in_context** → how often the correct abstract reached the LLM
- **per-class accuracy** → small models usually struggle most with "maybe"
"""

summary = preds.groupby("setup").agg(
    accuracy=("correct", "mean"),
    unknown_rate=("pred", lambda s: (s == "unknown").mean()),
    gold_in_context=("gold_retrieved", "mean"),
).round(3)

per_class = preds.pivot_table(index="setup", columns="label",
                              values="correct", aggfunc="mean").round(3)

display(summary)
display(per_class)

"""### 10.2 The key research link: retrieval quality → answer quality
Compare accuracy when the correct abstract **was** vs **was not** retrieved.
If accuracy is clearly higher when it was retrieved, that supports your research claim: **better retrieval → better, more grounded answers.**
"""

rag_only = preds[preds.setup != "LLM only (no retrieval)"]
rag_only.groupby(["setup", "gold_retrieved"])["correct"].mean().unstack().round(3)

