show(base_scores)

"""## Part 4 — Fine-tune the embedding model (the heart of the project)

**Goal:** teach MiniLM medical language, so a medical question lands near its matching abstract.

**How:**
- Take 10,000 (question, abstract) pairs from the unlabeled set.
- Group them into batches of 32.
- **MultipleNegativesRankingLoss**: in each batch, the model learns "question 1 ↔ abstract 1 is the match; abstracts 2–32 are wrong" and repeats this for every question.
- Bigger batches = more wrong answers to learn from = usually better.

**Time:** about 3–5 minutes per epoch on a T4.
"""

from sentence_transformers import InputExample, losses
from torch.utils.data import DataLoader

N_TRAIN = 10_000
sample = train_pool.shuffle(seed=SEED).select(range(N_TRAIN))

train_examples = [
    InputExample(texts=[r["question"], " ".join(r["context"]["contexts"])])
    for r in sample
]
print("Example question:", train_examples[0].texts[0])
print("Example abstract:", train_examples[0].texts[1][:300], "...")

"""### 4.1 Train
- `EPOCHS = 1` is a quick first run. Try 2–3 later and compare; that comparison is a good experiment to report.
- `warmup_steps` starts with tiny learning steps, like warming up before a run.
"""

ft_model = SentenceTransformer(BASE_MODEL, device=DEVICE)   # start from the same base model

train_loader = DataLoader(train_examples, shuffle=True, batch_size=32)
train_loss = losses.MultipleNegativesRankingLoss(ft_model)

EPOCHS = 1
ft_model.fit(
    train_objectives=[(train_loader, train_loss)],
    epochs=EPOCHS,
    warmup_steps=int(0.1 * len(train_loader) * EPOCHS),
    show_progress_bar=True,
)

FT_PATH = "mini-pubmedqa-finetuned"
