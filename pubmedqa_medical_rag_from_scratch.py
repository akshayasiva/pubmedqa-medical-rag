"""### 3.2 Measure baseline retrieval
For every test question, search all chunks and check whether chunks from its **own** abstract come back on top.

The evaluator reports several metrics. Focus on:
- **accuracy@1 / @5 / @10** → "Was the right abstract found in the top 1 / 5 / 10?" (same as Hit@K)
- **mrr@10** → how high it ranked

This is the score the fine-tuned model must beat.
"""

from sentence_transformers.evaluation import InformationRetrievalEvaluator

queries       = dict(zip(test_df.pubid, test_df.question))
corpus        = dict(zip(chunks_df.chunk_id, chunks_df.text))
relevant_docs = chunks_df.groupby("pubid")["chunk_id"].apply(set).to_dict()

ir_eval = InformationRetrievalEvaluator(
    queries=queries, corpus=corpus, relevant_docs=relevant_docs,
    accuracy_at_k=[1, 5, 10], precision_recall_at_k=[5, 10],
    mrr_at_k=[10], ndcg_at_k=[10], map_at_k=[10],
    name="pubmedqa", show_progress_bar=True,
)

def show(scores):
    if not isinstance(scores, dict):
        return scores
    return pd.Series({k.split("cosine_")[-1]: round(v, 4)
                      for k, v in scores.items() if "cosine" in k})

