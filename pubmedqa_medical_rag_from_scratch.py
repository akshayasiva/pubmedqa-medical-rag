"""### 1.4 Prevent data leakage
**Leakage** = the model sees test data during training, which makes scores look better than they really are.
We remove any training pair whose abstract id also appears in the test set.
"""

test_ids = set(test_df.pubid)
train_pool = unlabeled.filter(lambda r: str(r["pubid"]) not in test_ids)
