"""## Part 2 — Chunking

Our embedding model reads at most **128 tokens** (~90–100 words) at once; anything longer is cut off.
So we split each abstract into **100-word chunks with a 20-word overlap**.
- Overlap is like overlapping photos in a panorama, so no sentence gets lost at a cut.
- Each chunk remembers which abstract (`pubid`) it came from.
"""

def chunk_text(text, chunk_words=100, overlap=20):
    words = text.split()
    chunks, start = [], 0
    while start < len(words):
        chunks.append(" ".join(words[start:start + chunk_words]))
        if start + chunk_words >= len(words):
            break
        start += chunk_words - overlap
    return chunks

rows = []
for _, r in test_df.iterrows():
    for i, ch in enumerate(chunk_text(r["abstract"])):
        rows.append({"chunk_id": f"{r.pubid}_{i}", "pubid": r.pubid, "text": ch})

chunks_df = pd.DataFrame(rows)
